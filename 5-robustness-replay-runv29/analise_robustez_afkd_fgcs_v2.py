def _save(fig, stem: Path) -> None:
    for ext in (".pdf", ".png"):
        fig.savefig(str(stem) + ext, bbox_inches="tight", dpi=150)
    plt.close(fig)
    print(f"    Salvo: {stem.name}.pdf / .png")


def _print_summary(df: pd.DataFrame, theta_global: float, seed: int) -> None:
    tg = df[np.isclose(df["theta"], theta_global, atol=0.015)]
    if tg.empty:
        idx = (df["theta"] - theta_global).abs().idxmin()
        tg  = df.iloc[[idx - 1, idx]]  # pega vizinhança
    theta_used = float(tg["theta"].values[0])

    print(f"\n  ── Tabela comparativa com θ={theta_used:.3f} (seed={seed}) ──")
    print(f"  {'Modelo':<12} {'FailRate':>10} {'TTD bruto':>12} {'TTD efetivo':>14}")
    print(f"  {'-'*52}")
    for _, r in tg.iterrows():
        print(f"  {r['modelo']:<12} {r['FailRate']:>10.4f} "
              f"{r['TTD_bruto_s']:>12.4f} {r['TTD_efetivo_s']:>14.4f}")

    base_r = tg[tg["modelo"] == "Baseline"]
    kd_r   = tg[tg["modelo"] == "AF-KD"]
    if not base_r.empty and not kd_r.empty:
        delta_fr  = float(base_r["FailRate"].values[0])      - float(kd_r["FailRate"].values[0])
        delta_eff = float(base_r["TTD_efetivo_s"].values[0]) - float(kd_r["TTD_efetivo_s"].values[0])
        pct       = delta_eff / max(abs(float(base_r["TTD_efetivo_s"].values[0])), 1e-9) * 100
        print(f"\n  ✓ ΔFailRate  = {delta_fr:+.4f}  (AF-KD {'melhor' if delta_fr > 0 else 'pior'})")
        print(f"  ✓ ΔTTDef     = {delta_eff:+.4f}s ({pct:.1f}%)  (AF-KD {'melhor' if delta_eff > 0 else 'pior'})")


