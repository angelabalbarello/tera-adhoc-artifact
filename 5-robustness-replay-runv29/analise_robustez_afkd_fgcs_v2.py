def _compute_sym_table(
    y_true_fr, probs_base, probs_kd,
    theta_grid, m, window, dt
) -> pd.DataFrame:
    rows = []
    for thr in theta_grid:
        for label, probs in [("Baseline", probs_base), ("AF-KD", probs_kd)]:
            fr, _ = _failrate_for_thr(y_true_fr, probs, float(thr), m, window)
            ttds_pen  = _ttd_per_episode(y_true_fr, probs, float(thr), m, window, True)
            ttds_only = _ttd_per_episode(y_true_fr, probs, float(thr), m, window, False)
            rows.append({
                "theta":         round(float(thr), 3),
                "modelo":        label,
                "FailRate":      round(fr, 4),
                "TTD_bruto_s":   round(float(np.mean(ttds_only)) * dt, 4) if len(ttds_only) > 0 else float("nan"),
                "TTD_efetivo_s": round(float(np.mean(ttds_pen))  * dt, 4) if len(ttds_pen)  > 0 else float("nan"),
            })
    return pd.DataFrame(rows)


def _plot_analise1(df: pd.DataFrame, seed: int, out_dir: Path) -> None:
    fig, axes = plt.subplots(1, 3, figsize=(15, 4.5))
    fig.suptitle(
        f"Análise 1 — θ Simétrico Global (seed {seed})\n"
        "Mesmo limiar aplicado a Baseline e AF-KD",
        fontsize=12, fontweight="bold"
    )
    colors = {"Baseline": "#d62728", "AF-KD": "#1f77b4"}
    ls_map = {"Baseline": "--", "AF-KD": "-"}
    panels = [
        ("FailRate",      "FailRate (↓ melhor)",                           "FailRate"),
        ("TTD_bruto_s",   "TTD bruto — só detectados (s)\n⚠ exclui perdidos", "TTD bruto (s)"),
        ("TTD_efetivo_s", "TTD efetivo com penalidade (s)\n✓ métrica justa",   "TTD efetivo (s)"),
    ]
    for ax, (col, title, ylabel) in zip(axes, panels):
        for modelo, grp in df.groupby("modelo"):
            ax.plot(grp["theta"], grp[col],
                    color=colors[modelo], linestyle=ls_map[modelo],
                    linewidth=2, label=modelo, marker="o", markersize=4)
        ax.set_title(title, fontsize=10)
        ax.set_xlabel("θ (limiar simétrico)", fontsize=9)
        ax.set_ylabel(ylabel, fontsize=9)
        if col == "FailRate":
            ax.set_ylim(-0.02, 1.02)
        ax.legend(fontsize=9)
        ax.grid(True, alpha=0.35)
    plt.tight_layout()
    _save(fig, out_dir / f"analise1_theta_simetrico_seed{seed}")


