# ANÁLISE 2 — CURVA COBERTURA × TTD
# ══════════════════════════════════════════════════════════════════════════════

def _plot_analise2(
    y_true_fr, probs_base, probs_kd,
    theta_sym, seed, m, window, dt, out_dir: Path
) -> None:
    fig, axes = plt.subplots(1, 2, figsize=(13, 5))
    fig.suptitle(
        f"Análise 2 — Curva Cobertura × TTD (seed {seed})\n"
        "Independe de qualquer θ — revela episódios não detectados",
        fontsize=12, fontweight="bold"
    )
    penalty_s = window * dt

    # Painel esquerdo — curvas de cobertura
    ax = axes[0]
    for label, probs, color, ls in [
        ("Baseline", probs_base, "#d62728", "--"),
        ("AF-KD",    probs_kd,   "#1f77b4", "-"),
    ]:
        tgrid, cov, _ = _coverage_curve(y_true_fr, probs, theta_sym, m, window, dt)
        ax.plot(tgrid, cov, color=color, linestyle=ls, linewidth=2.2, label=label)

        ttds_only = _ttd_per_episode(y_true_fr, probs, theta_sym, m, window, False) * dt
        if len(ttds_only) > 0:
            ttd_b = float(np.mean(ttds_only))
            ax.axvline(ttd_b, color=color, linestyle=":", linewidth=1.4,
                       label=f"TTD bruto {label}={ttd_b:.2f}s")

    ax.axvline(penalty_s, color="black", linestyle=":", linewidth=1.2, alpha=0.5,
               label=f"Penalidade ≈{penalty_s:.1f}s")
    ax.set_xlabel("Orçamento de TTD (s)", fontsize=11)
    ax.set_ylabel("Fração de episódios críticos cobertos", fontsize=11)
    ax.set_title(
        f"θ simétrico={theta_sym:.2f} | m={m}\n"
        "Baseline trava antes de 100% — perdidos excluídos do TTD bruto",
        fontsize=9
    )
    ax.set_xlim(0, penalty_s * 1.05)
    ax.set_ylim(0, 1.06)
    ax.legend(fontsize=8.5)
    ax.grid(True, alpha=0.35)

    # Painel direito — histograma com penalidade
    ax2 = axes[1]
    bins = np.linspace(0, penalty_s * 1.08, 32)
    for label, probs, color in [
        ("Baseline", probs_base, "#d62728"),
        ("AF-KD",    probs_kd,   "#1f77b4"),
    ]:
        ttds = _ttd_per_episode(y_true_fr, probs, theta_sym, m, window, True) * dt
        ax2.hist(ttds, bins=bins, alpha=0.55, color=color, label=label, density=True)

    ax2.axvline(penalty_s, color="black", linestyle="--", linewidth=1.5,
                label=f"Penalidade ≈{penalty_s:.1f}s (não detectado)")
    ax2.set_xlabel("TTD efetivo (s) — inclui penalidade", fontsize=11)
    ax2.set_ylabel("Densidade", fontsize=11)
    ax2.set_title(
        "Baseline empilha massa na penalidade máxima\n"
        "⚠ Esses casos SÃO excluídos do TTD bruto da tabela",
        fontsize=9
    )
    ax2.legend(fontsize=8.5)
    ax2.grid(True, alpha=0.35)

    plt.tight_layout()
    _save(fig, out_dir / f"analise2_coverage_ttd_seed{seed}")


