# PRIMITIVAS TTD  (auto-contidas, sem dependência do runner)
# ══════════════════════════════════════════════════════════════════════════════

def _first_stable(probs: np.ndarray, onset: int, thr: float, m: int) -> Optional[int]:
    """Índice do primeiro frame de uma janela de m consecutivos >= thr."""
    count = 0
    for t in range(onset, len(probs)):
        if probs[t] >= thr:
            count += 1
            if count >= m:
                return t - m + 1
        else:
            count = 0
    return None


def _ttd_per_episode(
    y_true_fr: np.ndarray,
    frame_probs: np.ndarray,
    thr: float,
    m: int = 3,
    window: int = 96,
    penalize_miss: bool = True,
) -> np.ndarray:
    """
    Vetor de TTDs (em frames) para cada episódio crítico.
    penalize_miss=True  → episódios não detectados recebem (window - t0). [JUSTO]
    penalize_miss=False → episódios não detectados são excluídos.          [TRAPAÇA]
    """
    ttds = []
    for yt, yp in zip(y_true_fr, frame_probs):
        idx = np.where(yt > 0)[0]
        if len(idx) == 0:
            continue
        t0  = int(idx[0])
        det = _first_stable(yp, t0, thr, m)
        if det is not None:
            ttds.append(det - t0)
        elif penalize_miss:
            ttds.append(window - t0)
    return np.array(ttds, dtype=float)


def _coverage_curve(
    y_true_fr: np.ndarray,
    frame_probs: np.ndarray,
    thr: float,
    m: int = 3,
    window: int = 96,
    dt: float = 10.0 / 96,
    n_points: int = 300,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """(t_grid_s, coverage, ttds_penalizados_s)."""
    ttds_frames = _ttd_per_episode(y_true_fr, frame_probs, thr, m, window, penalize_miss=True)
    ttds_s      = ttds_frames * dt
    t_grid      = np.linspace(0.0, window * dt * 1.02, n_points)
    coverage    = np.array([(ttds_s <= t).mean() for t in t_grid])
    return t_grid, coverage, ttds_s


def _failrate_for_thr(y_true_fr, frame_probs, thr, m, window):
    miss = 0
    total = 0
    for yt, yp in zip(y_true_fr, frame_probs):
        idx = np.where(yt > 0)[0]
        if len(idx) == 0:
            continue
        total += 1
        if _first_stable(yp, int(idx[0]), thr, m) is None:
            miss += 1
    return miss / max(total, 1), total


