def run_fairness_analyses(
    seed: int,
    y_true_fr_te: np.ndarray,   # (N, T) labels de frame — conjunto de TESTE
    probs_base: np.ndarray,     # (N, T) frame_probs Baseline no TESTE
    probs_kd: np.ndarray,       # (N, T) frame_probs AF-KD no TESTE
    theta_global: float,        # θ simétrico (calibrado no baseline)
    theta_base: float,          # θ assimétrico original do baseline
    theta_kd: float,            # θ assimétrico original do AF-KD
    window: int = 96,
    m: int = 3,
    out_dir: str = "fairness_outputs",
) -> None:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    dt = 10.0 / window

    # Filtra só críticos
    crit = np.array([np.any(yt > 0) for yt in y_true_fr_te])
    yf   = y_true_fr_te[crit]
    pb   = probs_base[crit]
    pk   = probs_kd[crit]

    print(f"\n{'='*72}")
    print(f"  ANÁLISES DE ROBUSTEZ — seed={seed} | N_críticos={int(crit.sum())}")
    print(f"  θ_global={theta_global:.3f}  θ_base={theta_base:.3f}  θ_kd={theta_kd:.3f}")
    print(f"{'='*72}")

    theta_grid = np.round(np.linspace(0.25, 0.60, 14), 3)

    # ── Análise 1 ────────────────────────────────────────────────────────────
    print("  [1/3] Análise 1 — θ simétrico...")
    df_sym = _compute_sym_table(yf, pb, pk, theta_grid, m, window, dt)
    df_sym.to_csv(out / f"analise1_theta_simetrico_seed{seed}.csv", index=False)
    _plot_analise1(df_sym, seed, out)
    _print_summary(df_sym, theta_global, seed)

    # ── Análise 2 ────────────────────────────────────────────────────────────
    print("  [2/3] Análise 2 — Cobertura × TTD...")
    _plot_analise2(yf, pb, pk, theta_global, seed, m, window, dt, out)

    # ── Análise 3 ────────────────────────────────────────────────────────────
    print("  [3/3] Análise 3 — Sensibilidade do θ...")
    _plot_analise3(df_sym, seed, out)

    print(f"\n  Todos os arquivos em '{out}':")
    for f in sorted(out.glob(f"analise*seed{seed}*")):
        print(f"    {f.name}")


